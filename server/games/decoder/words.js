// На всякий случай уберём дубликаты и явный мусор внутри каждой группы
const CLEAN_GROUPS = {};
for (const [name, words] of Object.entries(WORD_GROUPS)) {
  CLEAN_GROUPS[name] = [...new Set(words)].filter(w => /^[А-ЯЁа-яё-]+$/.test(w));
}

const CLEAN_WORDS = Object.values(CLEAN_GROUPS).flat();

// `array.sort(() => Math.random() - 0.5)` даёт сильно смещённую перетасовку
// (некоторые перестановки выпадают в разы чаще других) — вместо этого честный
// Фишер-Йетс, даёт каждой перестановке равную вероятность
function shuffle(array) {
  const result = [...array];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

// тянет `count` слов, по возможности каждое из своей тематической группы —
// мутирует groupPool, вычёркивая использованные слова
function drawDiverse(groupPool, count) {
  const result = [];
  for (const g of shuffle(Object.keys(groupPool))) {
    if (result.length >= count) break;
    const pool = groupPool[g];
    if (pool.length) result.push(pool.pop());
  }
  // групп меньше, чем нужно слов (или какие-то опустели) — донабираем
  // откуда придётся, повторение темы внутри команды тут уже неизбежно
  while (result.length < count) {
    const remaining = Object.keys(groupPool).filter(g => groupPool[g].length);
    if (!remaining.length) break;
    const g = shuffle(remaining)[0];
    result.push(groupPool[g].pop());
  }
  return result;
}

// раздаёт слова на две команды по `count` штук; слова каждой команды по
// возможности из разных тематических групп, между командами пересечений нет
function drawTeamWords(count, excluded) {
  const excludeSet = excluded instanceof Set ? excluded : new Set(excluded || []);
  const groupPool = {};
  for (const [name, words] of Object.entries(CLEAN_GROUPS)) {
    groupPool[name] = shuffle(words.filter(w => !excludeSet.has(w)));
  }
  const teamA = drawDiverse(groupPool, count);
  const teamB = drawDiverse(groupPool, count);
  return { teamA, teamB };
}

